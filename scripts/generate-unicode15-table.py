#!/usr/bin/env python3
"""Generate the Unicode 15.0.0 unassigned code point tables for canonical text.

Canonical text is NFC as defined by Unicode 15.0.0. Go and TypeScript compute it
with their runtime normalizer, but split the text at every code point whose Age
is Unassigned in Unicode 15.0.0, so those code points keep their 15.0.0 default
properties on every runtime. This script turns DerivedAge-15.0.0.txt into the
range table both languages embed; the table never changes for another Unicode
version. Download the input from
https://www.unicode.org/Public/15.0.0/ucd/DerivedAge.txt and pass its path.
"""

import argparse
import hashlib
from pathlib import Path
import sys


ROOT = Path(__file__).resolve().parents[1]
GO_OUTPUT = ROOT / "internal/canonical/unicode15_table.go"
TS_OUTPUT = ROOT / "packages/protocol-types/src/unicode15-table.ts"
SOURCE_URL = "https://www.unicode.org/Public/15.0.0/ucd/DerivedAge.txt"
MAX_CODE_POINT = 0x10FFFF


def assigned_ranges(source):
    lines = source.splitlines()
    if not lines or lines[0].strip() != "# DerivedAge-15.0.0.txt":
        raise SystemExit("input is not DerivedAge-15.0.0.txt")
    ranges = []
    for line in lines:
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        code_points = data.split(";", 1)[0].strip()
        first, _, last = code_points.partition("..")
        ranges.append((int(first, 16), int(last or first, 16)))
    ranges.sort()
    for (_, previous_last), (first, _) in zip(ranges, ranges[1:]):
        if first <= previous_last:
            raise SystemExit("DerivedAge ranges overlap")
    return ranges


def unassigned_ranges(assigned):
    result, next_code_point = [], 0
    for first, last in assigned:
        if first > next_code_point:
            result.append((next_code_point, first - 1))
        next_code_point = last + 1
    if next_code_point <= MAX_CODE_POINT:
        result.append((next_code_point, MAX_CODE_POINT))
    return result


def table_digest(ranges):
    text = "".join(f"{first:04X}..{last:04X}\n" for first, last in ranges)
    return hashlib.sha256(text.encode("ascii")).hexdigest()


def header(comment, source_digest):
    return (
        f"{comment} Code generated by scripts/generate-unicode15-table.py; DO NOT EDIT.\n"
        f"{comment} Source: {SOURCE_URL}\n"
        f"{comment} Source SHA-256: {source_digest}\n"
    )


def go_source(ranges, source_digest):
    rows = []
    for index in range(0, len(ranges), 4):
        row = ", ".join(f"{{0x{first:04X}, 0x{last:04X}}}" for first, last in ranges[index:index + 4])
        rows.append(f"\t{row},\n")
    return (
        header("//", source_digest)
        + "\npackage canonical\n\n"
        + "// unicode15UnassignedRanges lists, in ascending order, the inclusive code point\n"
        + "// ranges whose Age is Unassigned in Unicode 15.0.0.\n"
        + "var unicode15UnassignedRanges = [...][2]rune{\n"
        + "".join(rows)
        + "}\n"
    )


def ts_source(ranges, source_digest):
    rows = []
    for index in range(0, len(ranges), 4):
        row = " ".join(f"0x{first:04X}, 0x{last:04X}," for first, last in ranges[index:index + 4])
        rows.append(f"  {row}\n")
    return (
        header("//", source_digest)
        + "\n// Inclusive first/last code point pairs, in ascending order, whose Age is\n"
        + "// Unassigned in Unicode 15.0.0.\n"
        + "export const UNICODE_15_UNASSIGNED_RANGES: readonly number[] = Object.freeze([\n"
        + "".join(rows)
        + "]);\n"
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("derived_age", type=Path, help="path to DerivedAge-15.0.0.txt")
    parser.add_argument("--check", action="store_true", help="fail if the committed tables differ")
    arguments = parser.parse_args()

    source = arguments.derived_age.read_bytes()
    source_digest = hashlib.sha256(source).hexdigest()
    ranges = unassigned_ranges(assigned_ranges(source.decode("utf-8")))
    outputs = {GO_OUTPUT: go_source(ranges, source_digest), TS_OUTPUT: ts_source(ranges, source_digest)}
    stale = [path for path, text in outputs.items() if not path.is_file() or path.read_text() != text]
    if arguments.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)}", file=sys.stderr)
    else:
        for path in stale:
            path.write_text(outputs[path])
    print(f"{len(ranges)} ranges, table sha256 {table_digest(ranges)}")
    return 1 if arguments.check and stale else 0


if __name__ == "__main__":
    sys.exit(main())
